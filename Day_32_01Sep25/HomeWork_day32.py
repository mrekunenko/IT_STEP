# Виводимо назви рецептів, які містять інгредієнт "томат"
print("Рецепти з томатом:")
for recipe in recipes:
    if "томат" in recipe:
        print(f"- {recipe}")

print()

# Знаходимо рецепт з найменшим часом приготування
fastest_recipe = min(recipes, key=lambda recipe: recipe.time)
print("Рецепт з найменшим часом приготування:")
fastest_recipe.display_info()

# Демонстрація роботи методу __gt__
print("Порівняння часу приготування:")
pizza = recipes[0]  # Піца (30 хв)
